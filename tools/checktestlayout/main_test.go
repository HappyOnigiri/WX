// layout は cmd/internal/tools 配下にファイルを並べた検査対象のrootを作る。
func layout(t *testing.T, exclusions string, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, exclusionsFileName), []byte(exclusions), 0o600); err != nil {
		t.Fatal(err)
	}
	for _, directory := range []string{"cmd", "internal", "tools"} {
		if err := os.Mkdir(filepath.Join(root, directory), 0o700); err != nil {
			t.Fatal(err)
		}
	}
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestMapTestFile(t *testing.T) {
	impls := map[string]bool{"store": true, "store_edges": true, "slots": true}
	for _, test := range []struct {
		base string
		want string
	}{
		{"store", "store"},
		{"store_edges", "store_edges"},
		{"store_coverage", "store"},
		{"slots_edges_matrix", "slots"},
		{"layout", ""},
	} {
		t.Run(test.base, func(t *testing.T) {
			if got := mapTestFile(test.base, impls); got != test.want {
				t.Fatalf("mapTestFile(%q) = %q, want %q", test.base, got, test.want)
			}
		})
	}
}

